//! WOW-CUSTODIAN-05 P0-6: fail-closed two-host cryptographic preflight.
//!
//! Do not confuse TWO SIGNATURES with TWO PHYSICAL/OPERATIONAL FAILURE DOMAINS.
//! One human can control two machines, two Ed25519 keys, two QUIC EndpointIds,
//! two ASNs and two operator pseudonyms. This module only proves two distinct
//! locally pinned pairs of service/operator keys signed fresh statements;
//! "physical independence" deliberately remains UNVERIFIED in every result.
//!
//! Actual network handshake, disk custody, signed AUDIT/FETCH permissions,
//! timestamp integrity, host/operator ownership and independence must be
//! checked by other components and out-of-band investigators. No access
//! rights, ratings, sanctions, STORE/FETCH or W4 are created or changed.
//! The statements contain NO W3/message/recipient IDs or private routes.
use crate::trust_w3::TrustRegistry;
use ed25519_dalek::{Signature, Signer, SigningKey, VerifyingKey};

const SERVICE_DOMAIN: &[u8] = b"WOW/W7/two-host/service-attestation/lab-v0\0";
const OPERATOR_DOMAIN: &[u8] = b"WOW/W7/two-host/operator-attestation/lab-v0\0";
const RESULT_DOMAIN: &[u8] = b"WOW/W7/two-host/private-transcript/lab-v0\0";
pub const MAX_PREFLIGHT_WINDOW_MS: u64 = 10 * 60 * 1_000;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RunChallenge {
    /// Generated by an independent verifier using a CSPRNG, never by C.
    /// Reuse of this 32-byte nonce across runs invalidates freshness.
    pub nonce: [u8; 32],
    /// Verifier-controlled monotonic/UTC policy inputs; untrusted clock fails.
    pub issued_at_ms: u64,
    pub deadline_ms: u64,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct HostStatement {
    pub run_nonce: [u8; 32],
    pub service_id: [u8; 16],
    pub service_epoch: u64,
    /// Actual TLS identity must be separately checked on the connection.
    pub claimed_tls_endpoint: [u8; 32],
    pub operator_id: [u8; 16],
    /// This is only an operator's CLAIM, not verified infrastructure fact.
    pub claimed_failure_domain: [u8; 16],
    pub attested_at_ms: u64,
    pub expires_at_ms: u64,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct SignedHostStatement {
    pub statement: HostStatement,
    pub service_signature: [u8; 64],
    pub operator_signature: [u8; 64],
}

/// Independently provisioned pins. Never fill these from untrusted statement
/// bytes or from a public peer card. Caller must validate real TLS handshakes
/// and separate actual operator ownership from these claims.
pub struct ExpectedHost<'a> {
    pub service_id: [u8; 16],
    pub service_epoch: u64,
    pub tls_endpoint: [u8; 32],
    pub operator_id: [u8; 16],
    pub pinned_operator_key: &'a VerifyingKey,
    pub expected_claimed_domain: [u8; 16],
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum PreflightError {
    InvalidChallenge,
    EntropyUnavailable,
    InvalidStatement,
    StaleOrFutureStatement,
    WrongChallenge,
    WrongService,
    WrongTlsEndpoint,
    WrongOperator,
    WrongDomainClaim,
    UntrustedOrRevokedService,
    InvalidServiceSignature,
    InvalidOperatorSignature,
    DuplicateServiceIdentity,
    DuplicateTlsIdentity,
    DuplicateOperatorIdentity,
    ReusedKeyAcrossRoles,
    SameClaimedFailureDomain,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Independence {
    /// Two valid crypto attestations are insufficient to establish physical
    /// or organizational independence. This is intentionally the ONLY state.
    RequiresOutOfBandVerification,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct PreflightReport {
    /// Private, challenge-scoped fingerprint for manual reconciliation only.
    /// Never publish it to MapShard; it correlates service/host identities.
    pub private_transcript_digest: [u8; 32],
    pub cryptographically_distinct_signers: bool,
    pub independence: Independence,
    /// This primitive cannot approve a real storage placement or sanction.
    pub permits_automatic_store_or_suspension: bool,
}

impl RunChallenge {
    /// Safe default: generate a fresh unpredictable nonce on the independent
    /// verifier, not in the custodian process. No private key is used.
    pub fn generate(
        issued_at_ms: u64, deadline_ms: u64,
    ) -> Result<Self, PreflightError> {
        let mut nonce = [0u8; 32];
        getrandom::fill(&mut nonce).map_err(|_| PreflightError::EntropyUnavailable)?;
        let challenge = Self { nonce, issued_at_ms, deadline_ms };
        challenge.validate(issued_at_ms)?;
        Ok(challenge)
    }

    pub fn validate(&self, now_ms: u64) -> Result<(), PreflightError> {
        if self.nonce == [0; 32] || self.issued_at_ms == 0
            || self.issued_at_ms > i64::MAX as u64
            || self.deadline_ms <= self.issued_at_ms
            || self.deadline_ms > i64::MAX as u64
            || self.deadline_ms - self.issued_at_ms > MAX_PREFLIGHT_WINDOW_MS
        {
            return Err(PreflightError::InvalidChallenge);
        }
        if now_ms < self.issued_at_ms || now_ms > self.deadline_ms {
            return Err(PreflightError::StaleOrFutureStatement);
        }
        Ok(())
    }
}

fn body(statement: &HostStatement) -> Vec<u8> {
    let mut bytes = Vec::with_capacity(1 + 32 + 16 + 8 + 32 + 16 + 16 + 8 + 8);
    bytes.push(0); // protocol version
    bytes.extend_from_slice(&statement.run_nonce);
    bytes.extend_from_slice(&statement.service_id);
    bytes.extend_from_slice(&statement.service_epoch.to_be_bytes());
    bytes.extend_from_slice(&statement.claimed_tls_endpoint);
    bytes.extend_from_slice(&statement.operator_id);
    bytes.extend_from_slice(&statement.claimed_failure_domain);
    bytes.extend_from_slice(&statement.attested_at_ms.to_be_bytes());
    bytes.extend_from_slice(&statement.expires_at_ms.to_be_bytes());
    bytes
}

fn signed_input(domain: &[u8], statement: &HostStatement) -> Vec<u8> {
    let data = body(statement);
    let mut result = Vec::with_capacity(domain.len() + data.len());
    result.extend_from_slice(domain);
    result.extend_from_slice(&data);
    result
}

fn structural_validation(statement: &HostStatement) -> Result<(), PreflightError> {
    if statement.run_nonce == [0; 32] || statement.service_id == [0; 16]
        || statement.service_epoch == 0
        || statement.service_epoch > i64::MAX as u64
        || statement.claimed_tls_endpoint == [0; 32]
        || statement.operator_id == [0; 16]
        || statement.claimed_failure_domain == [0; 16]
        || statement.attested_at_ms == 0
        || statement.expires_at_ms <= statement.attested_at_ms
        || statement.expires_at_ms > i64::MAX as u64
        || statement.expires_at_ms - statement.attested_at_ms > MAX_PREFLIGHT_WINDOW_MS
    {
        return Err(PreflightError::InvalidStatement);
    }
    Ok(())
}

/// Offline/on-host signing adapter. Test keys are NOT shipped with this
/// module; real keys must be held by two separately protected local signers.
/// The two signatures do NOT assert independent humans or physical machines.
pub fn sign_for_lab(
    statement: HostStatement,
    service_signer: &SigningKey,
    operator_signer: &SigningKey,
) -> Result<SignedHostStatement, PreflightError> {
    structural_validation(&statement)?;
    if service_signer.verifying_key() == operator_signer.verifying_key() {
        return Err(PreflightError::ReusedKeyAcrossRoles);
    }
    Ok(SignedHostStatement {
        statement,
        service_signature: service_signer.sign(
            &signed_input(SERVICE_DOMAIN, &statement),
        ).to_bytes(),
        operator_signature: operator_signer.sign(
            &signed_input(OPERATOR_DOMAIN, &statement),
        ).to_bytes(),
    })
}

fn verify_one(
    challenge: RunChallenge, now_ms: u64,
    signed: &SignedHostStatement, expected: &ExpectedHost<'_>,
    trusted_services: &TrustRegistry,
) -> Result<VerifyingKey, PreflightError> {
    structural_validation(&signed.statement)?;
    let s = &signed.statement;
    if s.run_nonce != challenge.nonce { return Err(PreflightError::WrongChallenge); }
    if s.service_id != expected.service_id || s.service_epoch != expected.service_epoch {
        return Err(PreflightError::WrongService);
    }
    if s.claimed_tls_endpoint != expected.tls_endpoint {
        return Err(PreflightError::WrongTlsEndpoint);
    }
    if s.operator_id != expected.operator_id {
        return Err(PreflightError::WrongOperator);
    }
    if s.claimed_failure_domain != expected.expected_claimed_domain {
        return Err(PreflightError::WrongDomainClaim);
    }
    if s.attested_at_ms < challenge.issued_at_ms || s.attested_at_ms > now_ms
        || s.expires_at_ms <= now_ms || s.expires_at_ms > challenge.deadline_ms
    {
        return Err(PreflightError::StaleOrFutureStatement);
    }
    let key = trusted_services.key_for(s.service_id, s.service_epoch)
        .map_err(|_| PreflightError::UntrustedOrRevokedService)?;
    key.verify_strict(
        &signed_input(SERVICE_DOMAIN, s),
        &Signature::from_bytes(&signed.service_signature),
    ).map_err(|_| PreflightError::InvalidServiceSignature)?;
    expected.pinned_operator_key.verify_strict(
        &signed_input(OPERATOR_DOMAIN, s),
        &Signature::from_bytes(&signed.operator_signature),
    ).map_err(|_| PreflightError::InvalidOperatorSignature)?;
    if key == expected.pinned_operator_key {
        return Err(PreflightError::ReusedKeyAcrossRoles);
    }
    Ok(*key)
}

/// Verifies fresh service+operator signature pairs under independently pinned
/// keys and requires distinct *claimed* failure domains. Cannot establish
/// host/operator independence or actually exercised QUIC; those remain human
/// acceptance gates and MUST NOT be inferred from this report.
pub fn verify_pair(
    challenge: RunChallenge, now_ms: u64,
    first: &SignedHostStatement, second: &SignedHostStatement,
    first_expected: &ExpectedHost<'_>, second_expected: &ExpectedHost<'_>,
    trusted_services: &TrustRegistry,
) -> Result<PreflightReport, PreflightError> {
    challenge.validate(now_ms)?;
    let first_key = verify_one(challenge, now_ms, first, first_expected, trusted_services)?;
    let second_key = verify_one(challenge, now_ms, second, second_expected, trusted_services)?;
    if first.statement.service_id == second.statement.service_id || first_key == second_key {
        return Err(PreflightError::DuplicateServiceIdentity);
    }
    if first.statement.claimed_tls_endpoint == second.statement.claimed_tls_endpoint {
        return Err(PreflightError::DuplicateTlsIdentity);
    }
    if first.statement.operator_id == second.statement.operator_id
        || first_expected.pinned_operator_key == second_expected.pinned_operator_key
    {
        return Err(PreflightError::DuplicateOperatorIdentity);
    }
    if first_key == *second_expected.pinned_operator_key
        || second_key == *first_expected.pinned_operator_key
    {
        return Err(PreflightError::ReusedKeyAcrossRoles);
    }
    if first.statement.claimed_failure_domain == second.statement.claimed_failure_domain {
        return Err(PreflightError::SameClaimedFailureDomain);
    }
    let mut hash = blake3::Hasher::new();
    hash.update(RESULT_DOMAIN);
    hash.update(&challenge.nonce);
    for signed in [first, second] {
        hash.update(&signed_input(SERVICE_DOMAIN, &signed.statement));
        hash.update(&signed.service_signature);
        hash.update(&signed.operator_signature);
    }
    Ok(PreflightReport {
        private_transcript_digest: *hash.finalize().as_bytes(),
        cryptographically_distinct_signers: true,
        independence: Independence::RequiresOutOfBandVerification,
        permits_automatic_store_or_suspension: false,
    })
}
